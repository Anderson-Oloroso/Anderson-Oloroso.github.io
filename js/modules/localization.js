export function getTranslation(language, key) {
  const translation = translations[language]?.[key];
  if (translation === undefined) {
    throw new Error(`Missing translation "${key}" for "${language}"`);
  }
  return translation;
}

function translate(language) {
  const dictionary = translations[language];
  if (!dictionary) {
    throw new Error(`Unsupported language: ${language}`);
  }

  document.documentElement.lang = language;

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    element.textContent = getTranslation(language, key);
  });

  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const key = element.dataset.i18nHtml;
    element.innerHTML = getTranslation(language, key);
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    const key = element.dataset.i18nAriaLabel;
    element.setAttribute('aria-label', getTranslation(language, key));
  });

  document.querySelector('meta[name="description"]').setAttribute('content', dictionary.pageDescription);
  document.querySelector('meta[property="og:description"]').setAttribute('content', dictionary.pageDescription);
  document.querySelectorAll('[data-i18n-alt]').forEach(element => {
    const key = element.dataset.i18nAlt;
    element.setAttribute('alt', getTranslation(language, key));
  });
  document.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
}

export function initLocalization() {
  const languageSelect = document.getElementById('language-select');
  if (!languageSelect) {
    throw new Error('Language selector was not found');
  }

  languageSelect.addEventListener('change', () => translate(languageSelect.value));
  translate(languageSelect.value);
}
